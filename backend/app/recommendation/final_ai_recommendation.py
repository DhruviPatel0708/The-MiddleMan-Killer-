def normalize_result(
    result,
):
    """
    Flattens common nested result structures.
    """

    if result is None:

        return {}

    if not isinstance(
        result,
        dict,
    ):

        return {}

    normalized = dict(
        result
    )

    nested_keys = [

        "final_decision",

        "decision",

        "recommendation",

        "financial",

        "market",

        "risk",

        "confidence",

    ]

    for key in nested_keys:

        nested = result.get(
            key
        )

        if isinstance(
            nested,
            dict,
        ):

            for (
                child_key,
                value,
            ) in nested.items():

                if child_key not in normalized:

                    normalized[
                        child_key
                    ] = value

    return normalized


