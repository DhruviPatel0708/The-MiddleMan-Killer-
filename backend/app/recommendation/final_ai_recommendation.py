    # ==================================================================
    # NUMERIC HELPER
    # ==================================================================

    @staticmethod
    def _number(
        value,
        default=0.0,
    ):
        """
        Safely converts a value into float.
        """

        if value is None:
            return default

        if isinstance(
            value,
            (int, float),
        ):
            return float(value)

        text = str(value)

        text = (
            text
            .replace("₹", "")
            .replace(",", "")
            .replace("%", "")
            .strip()
        )

        try:
            return float(text)

        except Exception:
            return default

    # ==================================================================
    # STRING HELPER
    # ==================================================================

    @staticmethod
    def _clean(
        value,
        default="NOT AVAILABLE",
    ):
        """
        Safely converts values into non-empty strings.
        """

        if value is None:
            return default

        text = str(value).strip()

        if not text:
            return default

        return text

    # ==================================================================
    # DYNAMIC SELL NOW VS WAIT
    # ==================================================================

    def determine_sell_wait(
        self,
        decision_result,
        net_profit,
        risk_level,
        confidence,
    ):
        """
        Dynamically determines the final Sell/Wait decision.

        Priority:

            1. Expected Net Profit
            2. Risk Level
            3. Confidence

        Possible outputs:

            SELL NOW
            SELL WITH CAUTION
            WAIT / REASSESS

        IMPORTANT:

        The Decision Intelligence recommendation is NOT blindly copied.

        The final recommendation is based primarily on the
        execution-level expected net profit.
        """

        risk_level = str(
            risk_level
        ).strip().upper()

        confidence = float(
            confidence
        )

        net_profit = float(
            net_profit
        )

        # ==============================================================
        # RULE 1
        # NEGATIVE PROFIT
        # ==============================================================

        if net_profit < 0:

            return "WAIT / REASSESS"

        # ==============================================================
        # RULE 2
        # ZERO PROFIT
        # ==============================================================

        if net_profit == 0:

            return "WAIT / REASSESS"

        # ==============================================================
        # RULE 3
        # POSITIVE PROFIT + LOW RISK + HIGH CONFIDENCE
        # ==============================================================

        if (
            net_profit > 0
            and risk_level == "LOW"
            and confidence >= 70
        ):

            return "SELL NOW"

        # ==============================================================
        # RULE 4
        # POSITIVE PROFIT + MEDIUM RISK
        # ==============================================================

        if (
            net_profit > 0
            and risk_level == "MEDIUM"
        ):

            return "SELL WITH CAUTION"

        # ==============================================================
        # RULE 5
        # POSITIVE PROFIT + HIGH RISK
        # ==============================================================

        if (
            net_profit > 0
            and risk_level == "HIGH"
        ):

            return "SELL WITH CAUTION"

        # ==============================================================
        # RULE 6
        # POSITIVE PROFIT + VERY LOW CONFIDENCE
        # ==============================================================

        if (
            net_profit > 0
            and confidence < 50
        ):

            return "WAIT / REASSESS"

        # ==============================================================
        # RULE 7
        # POSITIVE PROFIT + MODERATE CONFIDENCE
        # ==============================================================

        if (
            net_profit > 0
            and 50 <= confidence < 70
        ):

            return "SELL WITH CAUTION"

        # ==============================================================
        # SAFETY FALLBACK
        # ==============================================================

        return "WAIT / REASSESS"

    # ==================================================================
    # CHOOSE MARKET
    # ==================================================================

    def choose_market(
        self,
        decision_result,
        logistics_result,
    ):
        """
        Selects the best market from existing Decision Intelligence
        and Logistics outputs.
        """

        market = self._clean(
            decision_result.get(
                "best_market"
            ),
            "",
        )

        if market:
            return market

        market = self._clean(
            decision_result.get(
                "market"
            ),
            "",
        )

        if market:
            return market

        market = self._clean(
            logistics_result.get(
                "destination"
            ),
            "",
        )

        if market:
            return market

        market = self._clean(
            logistics_result.get(
                "best_destination"
            ),
            "",
        )

        if market:
            return market

        return "NOT AVAILABLE"

    # ==================================================================
    # CHOOSE BUYER
    # ==================================================================

    def choose_buyer(
        self,
        decision_result,
        profit_result,
        risk_result,
        auction_result,
    ):
        """
        Selects the buyer using existing execution outputs.

        Priority:

            Net Profit Optimization
            Risk-Aware Bidding
            AI Auction
        """

        # --------------------------------------------------------------
        # NET PROFIT OPTIMIZATION
        # --------------------------------------------------------------

        buyer = self._clean(
            profit_result.get(
                "buyer_name"
            ),
            "",
        )

        if buyer:
            return buyer

        buyer = self._clean(
            profit_result.get(
                "recommended_buyer"
            ),
            "",
        )

        if buyer:
            return buyer

        # --------------------------------------------------------------
        # RISK-AWARE BIDDING
        # --------------------------------------------------------------

        buyer = self._clean(
            risk_result.get(
                "buyer_name"
            ),
            "",
        )

        if buyer:
            return buyer

        buyer = self._clean(
            risk_result.get(
                "recommended_buyer"
            ),
            "",
        )

        if buyer:
            return buyer

        # --------------------------------------------------------------
        # AI AUCTION
        # --------------------------------------------------------------

        buyer = self._clean(
            auction_result.get(
                "buyer_name"
            ),
            "",
        )

        if buyer:
            return buyer

        buyer = self._clean(
            auction_result.get(
                "winner"
            ),
            "",
        )

        if buyer:
            return buyer

        return "NOT AVAILABLE"

    # ==================================================================
    # EXPECTED NET PROFIT
    # ==================================================================

    def get_net_profit(
        self,
        decision_result,
        profit_result,
    ):
        """
        Execution-level Net Profit Optimization gets priority.

        Decision Intelligence net profit is used only if the
        execution-level result is unavailable.
        """

        candidates = [

            profit_result.get(
                "net_profit"
            ),

            profit_result.get(
                "expected_net_profit"
            ),

            decision_result.get(
                "net_profit"
            ),

            decision_result.get(
                "expected_net_profit"
            ),

        ]

        for value in candidates:

            if value is not None:

                return self._number(
                    value
                )

        return 0.0

    # ==================================================================
    # RISK LEVEL
    # ==================================================================

    def get_risk_level(
        self,
        decision_result,
        risk_result,
    ):
        """
        Uses existing risk outputs.

        Risk-Aware Bidding is preferred over the broader
        Decision Intelligence risk level because the final
        recommendation concerns the actual selected execution.
        """

        # --------------------------------------------------------------
        # Risk-Aware Bidding
        # --------------------------------------------------------------

        candidates = [

            risk_result.get(
                "risk_level"
            ),

            decision_result.get(
                "risk_level"
            ),

        ]

        for value in candidates:

            if value is not None:

                text = str(
                    value
                ).strip()

                if text:

                    return text.upper()

        # --------------------------------------------------------------
        # Numeric risk fallback
        # --------------------------------------------------------------

        risk_score = None

        for key in [
            "combined_risk",
            "risk_score",
        ]:

            if key in risk_result:

                risk_score = self._number(
                    risk_result[key],
                    None,
                )

                if risk_score is not None:
                    break

        if risk_score is None:

            for key in [
                "risk_score",
                "decision_risk_score",
            ]:

                if key in decision_result:

                    risk_score = self._number(
                        decision_result[key],
                        None,
                    )

                    if risk_score is not None:
                        break

        if risk_score is not None:

            if risk_score < 30:
                return "LOW"

            if risk_score < 60:
                return "MEDIUM"

            return "HIGH"

        return "NOT AVAILABLE"

    # ==================================================================
    # CONFIDENCE
    # ==================================================================

    def get_confidence(
        self,
        decision_result,
    ):
        """
        Gets the existing Decision Intelligence confidence.

        If the source provides a 0-1 value, it is converted to
        a percentage.
        """

        candidates = [

            decision_result.get(
                "confidence"
            ),

            decision_result.get(
                "final_confidence"
            ),

            decision_result.get(
                "confidence_score"
            ),

        ]

        for value in candidates:

            if value is not None:

                confidence = self._number(
                    value
                )

                if 0 <= confidence <= 1:

                    confidence *= 100

                return max(
                    0.0,
                    min(
                        100.0,
                        confidence,
                    ),
                )

        return 0.0

    # ==================================================================
    # REASON
    # ==================================================================

    def generate_reason(
        self,
        sell_wait,
        market,
        buyer,
        net_profit,
        risk_level,
        confidence,
        decision_result,
        logistics_result,
    ):
        """
        Generates a reason consistent with the final recommendation.
        """

        reasons = []

        # ==============================================================
        # FINAL DECISION
        # ==============================================================

        if sell_wait == "SELL NOW":

            reasons.append(
                "The available transaction is profitable, "
                "with acceptable risk and sufficient confidence."
            )

        elif sell_wait == "SELL WITH CAUTION":

            reasons.append(
                "The available transaction is profitable, "
                "but the risk or confidence conditions require caution."
            )

        else:

            reasons.append(
                "The current available transaction does not "
                "provide a sufficiently attractive outcome to sell now."
            )

        # ==============================================================
        # NET PROFIT
        # ==============================================================

        if net_profit > 0:

            reasons.append(
                f"The expected net profit is "
                f"₹{net_profit:,.2f}."
            )

        elif net_profit < 0:

            reasons.append(
                f"The best available execution option produces "
                f"a negative expected net profit of "
                f"₹{abs(net_profit):,.2f}."
            )

            reasons.append(
                "Therefore, the system recommends waiting or "
                "reassessing the available buyer, price, or market."
            )

        else:

            reasons.append(
                "The expected net profit is approximately zero."
            )

        # ==============================================================
        # RISK
        # ==============================================================

        if risk_level == "LOW":

            reasons.append(
                "The selected transaction has a low risk level."
            )

        elif risk_level == "MEDIUM":

            reasons.append(
                "The selected transaction has a medium risk level."
            )

        elif risk_level == "HIGH":

            reasons.append(
                "The selected transaction has a high risk level."
            )

        # ==============================================================
        # MARKET
        # ==============================================================

        if market != "NOT AVAILABLE":

            reasons.append(
                f"{market} is the selected market based on "
                f"the available market and logistics signals."
            )

        # ==============================================================
        # BUYER
        # ==============================================================

        if buyer != "NOT AVAILABLE":

            reasons.append(
                f"{buyer} is the selected buyer based on "
                f"buyer matching, auction, risk and profit signals."
            )

        # ==============================================================
        # CONFIDENCE
        # ==============================================================

        if confidence >= 70:

            reasons.append(
                f"The recommendation confidence is high at "
                f"{confidence:.2f}%."
            )

        elif confidence >= 50:

            reasons.append(
                f"The recommendation confidence is moderate at "
                f"{confidence:.2f}%."
            )

        else:

            reasons.append(
                f"The recommendation confidence is limited at "
                f"{confidence:.2f}%."
            )

        return " ".join(
            reasons
        )

    # ==================================================================
    # GENERATE FINAL RECOMMENDATION
    # ==================================================================

    def generate(
        self,
        decision_result,
        auction_result,
        risk_result,
        profit_result,
        logistics_result,
    ):
        """
        Generates the final seven-field recommendation.
        """

        print()
        print("=" * 70)
        print("GENERATING FINAL AI RECOMMENDATION")
        print("=" * 70)

        # ==============================================================
        # NET PROFIT
        # ==============================================================

        net_profit = self.get_net_profit(
            decision_result,
            profit_result,
        )

        # ==============================================================
        # RISK
        # ==============================================================

        risk_level = self.get_risk_level(
            decision_result,
            risk_result,
        )

        # ==============================================================
        # CONFIDENCE
        # ==============================================================

        confidence = self.get_confidence(
            decision_result,
        )

        # ==============================================================
        # MARKET
        # ==============================================================

        market = self.choose_market(
            decision_result,
            logistics_result,
        )

        # ==============================================================
        # BUYER
        # ==============================================================

        buyer = self.choose_buyer(
            decision_result,
            profit_result,
            risk_result,
            auction_result,
        )

        # ==============================================================
        # SELL / WAIT
        # ==============================================================

        sell_wait = self.determine_sell_wait(
            decision_result,
            net_profit,
            risk_level,
            confidence,
        )

        # ==============================================================
        # REASON
        # ==============================================================

        reason = self.generate_reason(
            sell_wait,
            market,
            buyer,
            net_profit,
            risk_level,
            confidence,
            decision_result,
            logistics_result,
        )

        # ==============================================================
        # FINAL RESULT
        # ==============================================================

        result = {

            "sell_now_vs_wait":
                sell_wait,

            "choose_market":
                market,

            "choose_buyer":
                buyer,

            "expected_net_profit":
                round(
                    net_profit,
                    2,
                ),

            "risk_level":
                risk_level,

            "confidence":
                round(
                    confidence,
                    2,
                ),

            "reason":
                reason,

        }

        return result

    # ==================================================================
    # VALIDATE
    # ==================================================================

    def validate(
        self,
        result,
    ):
        """
        Validates the final seven required outputs.
        """

        required_fields = [

            "sell_now_vs_wait",

            "choose_market",

            "choose_buyer",

            "expected_net_profit",

            "risk_level",

            "confidence",

            "reason",

        ]

        # --------------------------------------------------------------
        # Required fields
        # --------------------------------------------------------------

        for field in required_fields:

            if field not in result:

                raise RuntimeError(
                    f"Final recommendation missing: {field}"
                )

        # --------------------------------------------------------------
        # Sell/Wait
        # --------------------------------------------------------------

        valid_decisions = {

            "SELL NOW",

            "SELL WITH CAUTION",

            "WAIT / REASSESS",

        }

        if result[
            "sell_now_vs_wait"
        ] not in valid_decisions:

            raise RuntimeError(
                "Invalid final Sell/Wait decision: "
                f"{result['sell_now_vs_wait']}"
            )

        # --------------------------------------------------------------
        # Market
        # --------------------------------------------------------------

        if not str(
            result["choose_market"]
        ).strip():

            raise RuntimeError(
                "Choose Market is empty."
            )

        # --------------------------------------------------------------
        # Buyer
        # --------------------------------------------------------------

        if not str(
            result["choose_buyer"]
        ).strip():

            raise RuntimeError(
                "Choose Buyer is empty."
            )

        # --------------------------------------------------------------
        # Net Profit
        # --------------------------------------------------------------

        if not isinstance(
            result["expected_net_profit"],
            (int, float),
        ):

            raise RuntimeError(
                "Expected Net Profit must be numeric."
            )

        # --------------------------------------------------------------
        # Risk
        # --------------------------------------------------------------

        valid_risk_levels = {

            "LOW",

            "MEDIUM",

            "HIGH",

        }

        if result[
            "risk_level"
        ] not in valid_risk_levels:

            raise RuntimeError(
                "Invalid risk level: "
                f"{result['risk_level']}"
            )

        # --------------------------------------------------------------
        # Confidence
        # --------------------------------------------------------------

        confidence = self._number(
            result["confidence"]
        )

        if not (
            0 <= confidence <= 100
        ):

            raise RuntimeError(
                "Confidence must be between 0 and 100."
            )

        # --------------------------------------------------------------
        # Reason
        # --------------------------------------------------------------

        if not str(
            result["reason"]
        ).strip():

            raise RuntimeError(
                "Reason is empty."
            )

        return True


